-- V1 — Esquema de Community-Alerts e índices espaciales
-- Idempotente: crea lo que falte tanto en una base vacía como en una base existente cuyas tablas generó
-- Hibernate (ddl-auto: update). Los índices dejan de depender de ddl-auto, que no crea índices GiST.
-- ═══════════════════════════════════════════════════════════════════

-- PostGIS la instala el administrador en public (imagen postgis/db-init); el rol del servicio solo la usa,
-- por eso los tipos van calificados con public.

CREATE TABLE IF NOT EXISTS road_alerts (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_alert_id      VARCHAR(255) UNIQUE,
    driver_id            VARCHAR(255)         NOT NULL,
    driver_name          VARCHAR(255),
    alert_type           VARCHAR(255)         NOT NULL,
    severity             VARCHAR(255)         NOT NULL,
    title                VARCHAR(255)         NOT NULL,
    description          VARCHAR(1000),
    road_corridor        VARCHAR(255),
    max_clearance_meters DOUBLE PRECISION,
    location             public.geometry(Point, 4326) NOT NULL,
    latitude             DOUBLE PRECISION,
    longitude            DOUBLE PRECISION,
    confirmations_count  INTEGER,
    is_active            BOOLEAN,
    reported_at          TIMESTAMP(6)         NOT NULL,
    synced_at            TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS road_alert_confirmations (
    alert_id     BIGINT       NOT NULL,
    user_id      VARCHAR(64)  NOT NULL,
    confirmed_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (alert_id, user_id)
);

CREATE TABLE IF NOT EXISTS community_alerts_outbox_events (
    id             UUID PRIMARY KEY,
    aggregate_type VARCHAR(100)   NOT NULL,
    aggregate_id   VARCHAR(100)   NOT NULL,
    event_type     VARCHAR(150)   NOT NULL,
    payload        TEXT           NOT NULL,
    occurred_at    TIMESTAMPTZ(6) NOT NULL,
    created_at     TIMESTAMPTZ(6) NOT NULL,
    published_at   TIMESTAMPTZ(6),
    attempts       INTEGER        NOT NULL,
    last_error     VARCHAR(2000)
);

-- Un voto se borra con su alerta. Se agrega aparte porque la tabla pudo crearla Hibernate sin la FK.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_alert_confirmations_alert') THEN
        DELETE FROM road_alert_confirmations c
         WHERE NOT EXISTS (SELECT 1 FROM road_alerts a WHERE a.id = c.alert_id);
        ALTER TABLE road_alert_confirmations
            ADD CONSTRAINT fk_alert_confirmations_alert
            FOREIGN KEY (alert_id) REFERENCES road_alerts (id) ON DELETE CASCADE;
    END IF;
END $$;

-- Índice funcional con la misma expresión que usan las consultas (a.location::geography en ST_DWithin):
-- deduplicación de reportes y GET /alerts/nearby dejan de recorrer toda la tabla.
CREATE INDEX IF NOT EXISTS idx_road_alerts_location_geog ON road_alerts USING GIST ((location::public.geography));

-- Ventana de deduplicación: mismo tipo de alerta reportado en los últimos minutos.
CREATE INDEX IF NOT EXISTS idx_road_alerts_type_reported ON road_alerts (alert_type, reported_at DESC);

CREATE INDEX IF NOT EXISTS idx_alert_type ON road_alerts (alert_type);
CREATE INDEX IF NOT EXISTS idx_alert_status ON road_alerts (is_active);
CREATE INDEX IF NOT EXISTS idx_alert_outbox_unpublished ON community_alerts_outbox_events (published_at, created_at);
