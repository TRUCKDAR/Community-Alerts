-- Botón SOS del conductor: alerta de pánico que no espera confirmaciones de la comunidad. client_event_id hace
-- idempotente el reintento (doble toque, cola offline). La torre la atiende (ACKNOWLEDGED).
CREATE TABLE IF NOT EXISTS sos_alerts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_event_id  UUID UNIQUE,
    driver_id        VARCHAR(255)   NOT NULL,
    driver_name      VARCHAR(150),
    vehicle_plate    VARCHAR(20),
    load_id          BIGINT,
    latitude         DOUBLE PRECISION NOT NULL,
    longitude        DOUBLE PRECISION NOT NULL,
    accuracy_meters  DOUBLE PRECISION,
    message          VARCHAR(500),
    status           VARCHAR(20)    NOT NULL,
    triggered_at     TIMESTAMPTZ(6) NOT NULL,
    received_at      TIMESTAMPTZ(6) NOT NULL,
    acknowledged_by  VARCHAR(255),
    acknowledged_at  TIMESTAMPTZ(6),
    CONSTRAINT sos_alerts_status_check CHECK (status IN ('ACTIVE', 'ACKNOWLEDGED'))
);

CREATE INDEX IF NOT EXISTS idx_sos_alerts_active ON sos_alerts (status, triggered_at DESC);

